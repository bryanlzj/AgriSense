"""
Alert Router

This module provides API endpoints for the Alert System.

Endpoints:
- GET /api/v1/alert/ - List alerts with filtering
- GET /api/v1/alert/{id} - Get specific alert
- PUT /api/v1/alert/{id} - Update alert (mark as read/acknowledged)
- DELETE /api/v1/alert/{id} - Delete alert
- PUT /api/v1/alert/bulk - Bulk update alerts
- DELETE /api/v1/alert/bulk - Bulk delete alerts
- GET /api/v1/alert/stats/summary - Get alert statistics
- POST /api/v1/alert/check - Manually trigger alert checks

Learning Notes:
- Alerts are automatically generated by the alert service
- Users can mark alerts as read or acknowledged
- Bulk operations allow managing multiple alerts at once
- Statistics provide overview of alert status
- Manual check endpoint allows on-demand alert generation
"""

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from sqlalchemy import desc, func
from typing import List
from datetime import datetime, timedelta

from database import get_db
from dependencies.auth import get_current_user
from models.user import User
from models.alert import Alert
from schemas.alert import (
    AlertResponse,
    AlertUpdate,
    AlertFilter,
    AlertStatistics,
    BulkAlertUpdate,
    AlertType,
    AlertSeverity
)
from services.alert_service import AlertService

router = APIRouter(prefix="/alert", tags=["alerts"])


@router.get("/", response_model=List[AlertResponse])
def list_alerts(
    filter_params: AlertFilter = Depends(),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    List alerts with filtering
    
    Filters:
    - type: Filter by alert type (weather, pest, sensor, system)
    - severity: Filter by severity (info, warning, critical)
    - is_read: Filter by read status
    - is_acknowledged: Filter by acknowledged status
    - skip: Number of records to skip (pagination)
    - limit: Maximum number of records to return
    
    Returns:
        List of alerts
    """
    query = db.query(Alert).filter(Alert.user_id == current_user.id)
    
    # Apply filters
    if filter_params.type:
        query = query.filter(Alert.type == filter_params.type.value)
    
    if filter_params.severity:
        query = query.filter(Alert.severity == filter_params.severity.value)
    
    if filter_params.is_read is not None:
        query = query.filter(Alert.is_read == filter_params.is_read)
    
    if filter_params.is_acknowledged is not None:
        query = query.filter(Alert.is_acknowledged == filter_params.is_acknowledged)
    
    # Order by created_at descending (newest first)
    query = query.order_by(desc(Alert.created_at))
    
    # Apply pagination
    alerts = query.offset(filter_params.skip).limit(filter_params.limit).all()
    
    return alerts


@router.get("/{alert_id}", response_model=AlertResponse)
def get_alert(
    alert_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Get a specific alert by ID
    
    Args:
        alert_id: Alert ID
        
    Returns:
        Alert details
        
    Raises:
        404: Alert not found
    """
    alert = db.query(Alert).filter(
        Alert.id == alert_id,
        Alert.user_id == current_user.id
    ).first()
    
    if not alert:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Alert not found"
        )
    
    return alert


@router.put("/{alert_id}", response_model=AlertResponse)
def update_alert(
    alert_id: int,
    alert_update: AlertUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Update an alert (mark as read/acknowledged)
    
    Args:
        alert_id: Alert ID
        alert_update: Update data
        
    Returns:
        Updated alert
        
    Raises:
        404: Alert not found
    """
    alert = db.query(Alert).filter(
        Alert.id == alert_id,
        Alert.user_id == current_user.id
    ).first()
    
    if not alert:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Alert not found"
        )
    
    # Update fields
    if alert_update.is_read is not None:
        alert.is_read = alert_update.is_read
    
    if alert_update.is_acknowledged is not None:
        alert.is_acknowledged = alert_update.is_acknowledged
    
    db.commit()
    db.refresh(alert)
    
    return alert


