@router.put("/bulk", response_model=dict)
def bulk_update_alerts(
    bulk_update: BulkAlertUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Bulk update multiple alerts
    
    Args:
        bulk_update: Bulk update data with alert IDs
        
    Returns:
        Number of alerts updated
    """
    # Get alerts
    alerts = db.query(Alert).filter(
        Alert.id.in_(bulk_update.alert_ids),
        Alert.user_id == current_user.id
    ).all()
    
    if not alerts:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No alerts found with the provided IDs"
        )
    
    # Update alerts
    updated_count = 0
    for alert in alerts:
        if bulk_update.is_read is not None:
            alert.is_read = bulk_update.is_read
        
        if bulk_update.is_acknowledged is not None:
            alert.is_acknowledged = bulk_update.is_acknowledged
        
        updated_count += 1
    
    db.commit()
    
    return {
        "message": f"Successfully updated {updated_count} alerts",
        "updated_count": updated_count
    }


@router.delete("/bulk", status_code=status.HTTP_200_OK)
def bulk_delete_alerts(
    alert_ids: List[int],
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Bulk delete multiple alerts
    
    Args:
        alert_ids: List of alert IDs to delete
        
    Returns:
        Number of alerts deleted
    """
    # Get alerts
    alerts = db.query(Alert).filter(
        Alert.id.in_(alert_ids),
        Alert.user_id == current_user.id
    ).all()
    
    if not alerts:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No alerts found with the provided IDs"
        )
    
    # Delete alerts
    deleted_count = len(alerts)
    for alert in alerts:
        db.delete(alert)
    
    db.commit()
    
    return {
        "message": f"Successfully deleted {deleted_count} alerts",
        "deleted_count": deleted_count
    }


@router.get("/stats/summary", response_model=AlertStatistics)
def get_alert_statistics(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Get alert statistics
    
    Returns:
        Alert statistics including:
        - Total alerts
        - Unread alerts
        - Unacknowledged alerts
        - Alerts by type
        - Alerts by severity
        - Recent critical alerts (last 24 hours)
    """
    # Total alerts
    total_alerts = db.query(func.count(Alert.id)).filter(
        Alert.user_id == current_user.id
    ).scalar()
    
    # Unread alerts
    unread_alerts = db.query(func.count(Alert.id)).filter(
        Alert.user_id == current_user.id,
        Alert.is_read == False
    ).scalar()
    
    # Unread alerts (no is_acknowledged field, using is_read instead)
    # Note: The Alert model doesn't have is_acknowledged, only is_read
    
    # Alerts by type
    alerts_by_type = {}
    for alert_type in AlertType:
        count = db.query(func.count(Alert.id)).filter(
            Alert.user_id == current_user.id,
            Alert.alert_type == alert_type
        ).scalar()
        alerts_by_type[alert_type.value] = count
    
    # Alerts by severity
    alerts_by_severity = {}
    for severity in AlertSeverity:
        count = db.query(func.count(Alert.id)).filter(
            Alert.user_id == current_user.id,
            Alert.severity == severity
        ).scalar()
        alerts_by_severity[severity.value] = count
    
    # Recent critical alerts (last 24 hours)
    one_day_ago = datetime.utcnow() - timedelta(days=1)
    recent_critical_alerts = db.query(func.count(Alert.id)).filter(
        Alert.user_id == current_user.id,
        Alert.severity == AlertSeverity.CRITICAL,
        Alert.created_at >= one_day_ago
    ).scalar()
    
    return AlertStatistics(
        total_alerts=total_alerts,
        unread_alerts=unread_alerts,
        unacknowledged_alerts=unread_alerts,  # Using unread_alerts since is_acknowledged doesn't exist
        alerts_by_type=alerts_by_type,
        alerts_by_severity=alerts_by_severity,
        recent_critical_alerts=recent_critical_alerts
    )


@router.post("/check", response_model=dict)
def check_alerts(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Manually trigger alert checks
    
    This endpoint runs all alert checks:
    - Sensor data thresholds
    - Pest detections
    - Weather conditions (if available)
    
    Returns:
        Number of new alerts generated
    """
    # Run alert checks
    new_alerts = AlertService.run_alert_checks(db, current_user.id)
    
    return {
        "message": f"Alert check completed. Generated {len(new_alerts)} new alerts.",
        "new_alerts_count": len(new_alerts),
        "alert_ids": [alert.id for alert in new_alerts]
    }
